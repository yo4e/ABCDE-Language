"""Generate static-viewer data from the Python reference and its shared JSON.

No hand-edited browser dictionary or diagnostic translations. Run with --check in
validation; generated assets are committed so viewers need only a browser.
"""
import argparse
import ast
import json
from pathlib import Path
import sys
import unicodedata

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from abcde.interpreter import EXAMPLES, LANGUAGE, MAX_INPUT, analyze, reverse  # noqa: E402


def messages():
    result = {}
    source = ast.parse((ROOT / "abcde/interpreter.py").read_text(encoding="utf-8"))
    for node in ast.walk(source):
        if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Name):
            continue
        if node.func.id not in ("ParseError", "diagnostic"):
            continue
        code, en, ja = node.args[:3]
        if not isinstance(code, ast.Constant):
            if isinstance(code, ast.BinOp) and isinstance(code.left, ast.Constant) and code.left.value == "UNSPECIFIED_":
                continue  # Expanded below from actual reference output.
            raise ValueError("Unrecognized diagnostic code; update the generator.")
        values = []
        for value in (en, ja):
            if code.value == "INVALID_ATOM" and isinstance(value, ast.BinOp):
                value = value.left  # Shared prefix; the engine appends the input word.
            if not isinstance(value, ast.Constant):
                if code.value == "LEGACY_READING":
                    break  # Comes directly from language.json.
                raise ValueError("Unrecognized diagnostic message: " + code.value)
            values.append(value.value)
        if len(values) == 2:
            result[code.value] = dict(zip(("en", "ja"), values))
    for note in analyze("DA")["sentences"][0]["diagnostics"]:
        if note["code"].startswith("UNSPECIFIED_"):
            result[note["code"]] = {lang: note[lang] for lang in ("en", "ja")}
    return result


def render():
    # Python's casefold/isspace differ from JS lower-case/\s. Ship the reference's
    # small Unicode tables, avoiding locale-dependent or approximate matching.
    folds, spaces = {}, []
    for number in range(sys.maxunicode + 1):
        char = chr(number)
        if char.casefold() != char:
            folds[char] = char.casefold()
        if char.isspace():
            spaces.append(char)
    payload = {"language": LANGUAGE, "examples": EXAMPLES, "max_input": MAX_INPUT,
               "messages": messages(), "casefold": folds, "whitespace": spaces,
               "unicode_version": unicodedata.unidata_version, "reverse_note": reverse("")["note"]}
    return ("// Generated by tools/build_static.py. Do not edit; change the Python/JSON sources.\n"
            "globalThis.ABCDE_DATA = " + json.dumps(payload, ensure_ascii=True, separators=(",", ":")) + ";\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "docs/data.js"
    expected = render()
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != expected:
            parser.exit(1, "Static data is stale. Run python3 tools/build_static.py\n")
        print("Static data is current.")
    else:
        output.write_text(expected, encoding="utf-8")
        print("Generated docs/data.js")


if __name__ == "__main__":
    main()
