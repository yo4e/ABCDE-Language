"""Generate readable views of the shared language/phrase data; --check is read-only."""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from abcde.interpreter import EXAMPLES, LANGUAGE, analyze, parse_term  # noqa: E402


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", "<br>")


def table(headers, rows):
    lines = ["| " + " | ".join(map(cell, headers)) + " |",
             "| " + " | ".join("---" for _ in headers) + " |"]
    lines += ["| " + " | ".join(map(cell, row)) + " |" for row in rows]
    return "\n".join(lines)


def atom_table():
    return table(["Atom", "IPA", "Core field", "意味の核"], [
        ["`" + atom + "`", "[" + entry["ipa"] + "]", entry["en"], entry["ja"]]
        for atom, entry in LANGUAGE["atoms"].items()])


def marker_table():
    grammar = LANGUAGE["grammar"]
    rows = [["`" + marker + "`", value, "whole sentence / 文全体"]
            for group in ("moods", "tenses") for marker, value in grammar[group].items()]
    rows.append(["`" + grammar["negation"] + "`", "negation / 否定", "one attached term / 直結する1語"])
    return table(["Marker", "Meaning", "Scope"], rows)


def quick_table():
    ids = {"want_water", "do_not_eat", "help_me", "help_other", "return_three_days"}
    return table(["ABCDE", "日本語候補", "English candidate"], [
        ["`" + e["abcde"] + "`", e["ja"], e["en"]] for e in EXAMPLES if e["id"] in ids])


def legacy_table():
    return table(["Word", "Retired reading / action", "旧解釈と対応"], [
        ["`" + word + "`", note["en"], note["ja"]] for word, note in LANGUAGE["legacy"].items()])


def dictionary():
    rows = []
    for word, entry in LANGUAGE["conventions"].items():
        term = parse_term(word)
        rows.append(["`" + word + "`", " + ".join(term["atoms"]),
                     term["literal"]["en"] + " / " + term["literal"]["ja"],
                     "; ".join(r["en"] + " / " + r["ja"] for r in entry["readings"]),
                     entry["note"]["en"] + " / " + entry["note"]["ja"]])
    return "\n\n".join([
        "# ABCDE dictionary / 辞書",
        "<!-- Generated by tools/build_docs.py; edit abcde/data/language.json instead. -->",
        "Language version: `" + LANGUAGE["version"] + "`. Every specific reading below is a **convention**, not a new atom.\n"
        "個別の訳語はすべて慣用です。直訳はアトムから生成します。複数候補は文脈なしに選びません。\n"
        "Quantities and DE- apply to the whole term; the listed readings are for the unmodified base word.\n"
        "数量・否定は語全体にかかり、表の慣用候補は基本語の読みです。",
        "## Atoms / アトム", atom_table(),
        "## Conventional readings / 慣用の読み",
        table(["Word", "Atoms", "Structural gloss / 直訳", "Candidates / 候補", "Context / 条件"], rows),
        "## Time convention / 時間の慣用", LANGUAGE["time_convention"]["en"], LANGUAGE["time_convention"]["ja"],
        "## Retired v0 readings / 廃止した旧解釈", legacy_table(),
        "Unknown compounds remain decomposable. Absence from this table is not a spelling error.\n"
        "未登録の合成語も分解できます。未登録と文法違反は別です。See [specification](specification.md) and [migration](migration.md).",
    ]) + "\n"


def examples():
    parts = ["# ABCDE examples / 例文",
             "<!-- Generated by tools/build_docs.py; edit abcde/data/examples.json instead. -->",
             "Language version: `" + LANGUAGE["version"] + "`. Core glosses preserve fields and roles; natural readings are conventional candidates.\n"
             "構造と慣用訳を分離します。自然訳を確定訳として扱わず、前提と省略を確認してください。\n"
             "All examples are validated by the interpreter and tests. Reverse inputs are exact phrasebook entries, not a free-text translator."]
    for example in EXAMPLES:
        sentence = analyze(example["abcde"])["sentences"][0]
        if sentence["status"] == "invalid":
            raise ValueError("Invalid example: " + example["id"])
        parts += ["## " + example["id"], "```text\n" + example["abcde"] + "\n```",
                  "**" + example["ja"] + " / " + example["en"] + "**",
                  "State: `" + sentence["status"] + "`; mood: `" + sentence["mood"] + "`; tense: `" + sentence["tense"] + "`.",
                  table(["Term", "Atoms", "直訳", "Structural gloss"], [[
                      "`" + term["surface"] + "`", " + ".join(term["atoms"]) or "opaque external",
                      term["literal"]["ja"], term["literal"]["en"]] for term in sentence["terms"]])]
        for index, interpretation in enumerate(sentence["interpretations"], 1):
            parts.append("Structure " + str(index) + ": " + interpretation["literal"]["en"] + "\n\n" + interpretation["literal"]["ja"])
        if sentence["relation"]:
            parts.append("`E`: relation type unspecified / 関係の種類は未指定。")
        parts += ["**Assumptions / 条件:** " + example["assumptions"]["en"] + "\n\n" + example["assumptions"]["ja"]]
        aliases = example["reverse"]["ja"] + example["reverse"]["en"]
        parts.append("Reverse inputs / 逆翻訳の対応入力: " + ("; ".join("`" + a + "`" for a in aliases) if aliases else "none / なし"))
    return "\n\n".join(parts) + "\n"


def replace_section(text, name, content):
    start, end = "<!-- BEGIN GENERATED: " + name + " -->", "<!-- END GENERATED: " + name + " -->"
    if text.count(start) != 1 or text.count(end) != 1:
        raise ValueError("Missing/duplicate generated section: " + name)
    return re.sub(re.escape(start) + r".*?" + re.escape(end),
                  lambda _: start + "\n\n" + content + "\n\n" + end, text, flags=re.DOTALL)


def render_all():
    result = {"dictionary.md": dictionary(), "examples.md": examples()}
    sections = {
        "README.md": {"atoms": atom_table(), "quick": quick_table()},
        "README_JP.md": {"atoms": atom_table(), "quick": quick_table()},
        "specification.md": {"atoms": atom_table(), "markers": marker_table(),
                             "time": LANGUAGE["time_convention"]["en"] + "\n\n" + LANGUAGE["time_convention"]["ja"]},
        "migration.md": {"legacy": legacy_table()},
    }
    for name, replacements in sections.items():
        text = (ROOT / name).read_text(encoding="utf-8")
        for section, content in replacements.items():
            text = replace_section(text, section, content)
        result[name] = text
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, content in render_all().items():
        path = ROOT / name
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(name)
            if not args.check:
                path.write_text(content, encoding="utf-8")
    if args.check and stale:
        print("Stale generated documents: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("Generated documents are current." if args.check else "Generated: " + (", ".join(stale) or "already current"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
